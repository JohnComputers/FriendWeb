export const makePerson = (
  firstName: string,
  extra: Partial<Person> = {},
): Person => {
  const now = new Date().toISOString();
  return {
    id: crypto.randomUUID(),
    firstName: firstName.trim(),
    tags: [],
    groups: [],
    custom: {},
    dates: {},
    metadata: {},
    createdAt: now,
    updatedAt: now,
    ...extra,
  };
};

